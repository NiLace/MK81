"""gen_nn_blob.py — embed the shipped neural power stages (nn/*.bnn2) in a C header so the
plugin binds them with bn_nn_lstm_bind() at instantiate: no file I/O, no bundle path, RT-safe.
  python3 tools/gen_nn_blob.py build/mk81_gen/bn_nn_weights.h
The four arms are indexed by (head, us): 0 = 100 W UK, 1 = 50 W UK, 2 = 100 W US, 3 = 50 W US; the plugin's slot
index is head + 2*us."""
import sys
from pathlib import Path
# The plugin ships ONE power-stage engine, the LSTM-32 (no HQ option): four slots, one per variant, indexed
# head + 2*us. Other weight sets (the LSTM-64 ones, older nets) stay in nn/ (the parity gate, `make mk81-nn-lstm`,
# still validates them); none is embedded.
# The 100 W UK slot uses lk_h32cr (epoch 250 of the retrain on the leakage-rule truth, kept by
# --ckpt-rule last-sane) over b27h32: worst-of-4 +12.98 vs +12.95, better on 3 of 4 takes and on 57 of 72 VAL sets.
# The other three slots use their B27 nets.
ARMS = [("lk_h32cr", 0, 0), ("b27v50_32", 1, 0), ("b27vus_32", 0, 1), ("b27v50us_32", 1, 1)]
out = Path(sys.argv[1]); out.parent.mkdir(parents=True, exist_ok=True)
NN = Path("nn"); SUF = lambda h, u: ""
# EVALUATION builds only (never the shipped header): `--all path/to/candidate.bnn2` puts ONE candidate in all four
# slots, so a trained arm can be scored inside the plugin (and the four slots share one training rate).
if len(sys.argv) > 3 and sys.argv[2] == "--all":
    cand = Path(sys.argv[3]); NN = cand.parent; SUF = lambda h, u: f"_{h}{u}"
    ARMS = [(cand.stem, h, u) for _, h, u in ARMS]
lines = ["/* generated by tools/gen_nn_blob.py from the .bnn2 weight sets under nn -- do not edit */",
         "#ifndef BN_NN_WEIGHTS_H", "#define BN_NN_WEIGHTS_H", "#include <stddef.h>", f"#define BN_NN_N_ARMS {len(ARMS)}"]
for tag, head, us in ARMS:
    b = (NN / f"{tag}.bnn2").read_bytes()
    lines.append(f"/* {tag}: head {head} us {us}, {len(b)} bytes */")
    lines.append(f"static const unsigned char bn_nn_blob_{tag}{SUF(head, us)}[{len(b)}] __attribute__((aligned(16))) = {{")
    for i in range(0, len(b), 24):
        lines.append("  " + ",".join(str(x) for x in b[i:i + 24]) + ",")
    lines.append("};")
# xlive: a net trained on w2 rendered with the EXACT node X (nn_datos.py --w2-vx, trainer
# --w2-suffix w2x) carries a sidecar `<tag>.xlive` next to its .bnn2; for that arm the plugin feeds the preamp the loaded
# supply's node X instead of holding it at rest. A net without the sidecar learned the preamp's sag from its rail input
# and must keep the hold, or it applies the sag twice.
xl = lambda tag: 1 if (NN / f"{tag}.xlive").is_file() else 0
lines.append("static const struct { const unsigned char* blob; size_t bytes; int head, us, xlive; const char* tag; } bn_nn_arms[BN_NN_N_ARMS] = {")
for tag, head, us in ARMS:
    lines.append(f"  {{ bn_nn_blob_{tag}{SUF(head, us)}, sizeof bn_nn_blob_{tag}{SUF(head, us)}, {head}, {us}, {xl(tag)}, \"{tag}\" }},")
lines.append("};"); lines.append("#endif")
out.write_text("\n".join(lines) + "\n"); print(f"wrote {out}: {sum((NN / f'{t}.bnn2').stat().st_size for t, _, _ in ARMS)} bytes of weights in {len(ARMS)} arm slots")
