/* gen_nn_rest.c — precompute each shipped arm's REST state and emit it as a header.
 *
 * WHY. Settling all four LSTM arms for 0.5 s each in `instantiate`, on every instantiation, costs
 * 4 x 48000 steps = 3910 M instructions = 0.40 s of the 0.417 s it would take to load the plugin,
 * which is 3.5x what processing TWO SECONDS of audio costs. And it would run ALWAYS, also in the
 * preamp-only build, where the net is compiled out of run().
 *
 * The settled state is DETERMINISTIC given the blob — it is just h_rest/c_rest/y_rest — so it is a
 * generated constant like any other in this project, not something to recompute per instance.
 *
 * ⭐ It is generated in C, by calling the engine's OWN bn_nn_lstm_settle with the same arguments
 * instantiate would use, so the table is BIT-IDENTICAL to what the settle produced. A Python
 * reimplementation would not be. Its gate (bn_test_nn_rest) re-runs the settle and demands equality,
 * so the table cannot rot when a weight set is retrained. */
#include <stdio.h>
#include <string.h>
#include "bn_nn_lstm.h"
#include "bn_nn_weights.h"

int main(int argc, char** argv)
{
    if (argc < 2) { fprintf(stderr, "usage: %s <out.h>\n", argv[0]); return 2; }
    static BnNnLstm nn[BN_NN_N_ARMS];
    for (int k = 0; k < BN_NN_N_ARMS; ++k) {
        if (bn_nn_lstm_bind(&nn[k], bn_nn_arms[k].blob, bn_nn_arms[k].bytes) != 0) {
            fprintf(stderr, "bind failed on arm %d (%s)\n", k, bn_nn_arms[k].tag); return 3;
        }
    }
    /* same rule as instantiate: the settle length comes from arm 0's training rate */
    const int settle_n = (int)(0.5 * (double)nn[0].fs);
    FILE* f = fopen(argv[1], "w");
    if (!f) { fprintf(stderr, "cannot write %s\n", argv[1]); return 4; }
    fprintf(f, "/* generated by tools/gen_nn_rest.c -- do not edit.\n"
               " * Each shipped arm's settled rest state (P12): what instantiate used to recompute\n"
               " * every time, at 0,40 s a go. Gate: `make mk81-nn-rest`. */\n");
    fprintf(f, "#ifndef BN_NN_REST_H\n#define BN_NN_REST_H\n");
    fprintf(f, "#define BN_NN_REST_SETTLE_N %d\n", settle_n);
    fprintf(f, "static const float BN_NN_REST_H_TAB[%d][%d] = {\n", BN_NN_N_ARMS, BN_NN_LSTM_MAX_H);
    for (int k = 0; k < BN_NN_N_ARMS; ++k) {
        const float y = bn_nn_lstm_settle(&nn[k], settle_n, 0.0f, 0.5f, 0.0f,
                                          (float)bn_nn_arms[k].head, (float)bn_nn_arms[k].us);
        (void)y;
        fprintf(f, "  { /* %s */\n   ", bn_nn_arms[k].tag);
        for (int i = 0; i < BN_NN_LSTM_MAX_H; ++i)
            fprintf(f, " %.9ef,%s", (double)nn[k].h_rest[i], (i % 6 == 5) ? "\n   " : "");
        fprintf(f, " },\n");
    }
    fprintf(f, "};\nstatic const float BN_NN_REST_C_TAB[%d][%d] = {\n", BN_NN_N_ARMS, BN_NN_LSTM_MAX_H);
    for (int k = 0; k < BN_NN_N_ARMS; ++k) {
        fprintf(f, "  { /* %s */\n   ", bn_nn_arms[k].tag);
        for (int i = 0; i < BN_NN_LSTM_MAX_H; ++i)
            fprintf(f, " %.9ef,%s", (double)nn[k].c_rest[i], (i % 6 == 5) ? "\n   " : "");
        fprintf(f, " },\n");
    }
    fprintf(f, "};\nstatic const float BN_NN_REST_Y_TAB[%d] = {", BN_NN_N_ARMS);
    for (int k = 0; k < BN_NN_N_ARMS; ++k) fprintf(f, " %.9ef,", (double)nn[k].y_rest);
    fprintf(f, " };\n#endif\n");
    fclose(f);
    printf("wrote %s: %d arms settled over %d samples\n", argv[1], BN_NN_N_ARMS, settle_n);
    return 0;
}
